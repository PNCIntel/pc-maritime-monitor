-- Preflight: inspect returned counts. Explicitly abort if any ambiguous or mismatched matches.
DO $$
DECLARE ambiguous bigint; mismatched bigint;
BEGIN
  SELECT count(*) INTO ambiguous FROM (
    SELECT r.source_record_id
    FROM recaap_geo_repair r
    JOIN public.pc_events e
      ON e.metadata->>'source_dataset'='recaap_incidents_2024_2026'
     AND e.metadata->>'source_record_id'=r.source_record_id
    GROUP BY r.source_record_id HAVING count(*)<>1
  ) duplicates;
  SELECT count(*) INTO mismatched
  FROM recaap_geo_repair r
  JOIN public.pc_events e ON e.metadata->>'source_dataset'='recaap_incidents_2024_2026'
     AND e.metadata->>'source_record_id'=r.source_record_id
  WHERE (e.start_date AT TIME ZONE 'UTC')::date IS DISTINCT FROM r.incident_date
     OR lower(trim(e.metadata->>'vessel_name')) IS DISTINCT FROM lower(trim(r.vessel_name));
  IF ambiguous > 0 OR mismatched > 0 THEN
    RAISE EXCEPTION 'ReCAAP geographic repair stopped: ambiguous IDs %, mismatched date/name %', ambiguous, mismatched;
  END IF;
END $$;
-- Preserve existing geography and provenance; do not overwrite conflicting coordinates.
WITH unique_matches AS (
 SELECT e.event_id,r.lat,r.lon
 FROM public.pc_events e
 JOIN recaap_geo_repair r ON e.metadata->>'source_record_id'=r.source_record_id
 WHERE e.metadata->>'source_dataset'='recaap_incidents_2024_2026'
   AND r.lat BETWEEN -90 AND 90 AND r.lon BETWEEN -180 AND 180
   AND NOT (e.metadata ? 'latitude' OR e.metadata ? 'longitude' OR e.metadata ? 'lat' OR e.metadata ? 'lon' OR e.metadata ? 'coordinates' OR e.metadata ? 'geometry')
), updated AS (
 UPDATE public.pc_events e
 SET metadata=jsonb_set(jsonb_set(jsonb_set(
      coalesce(e.metadata,'{}'::jsonb),
      '{latitude}',to_jsonb(u.lat),true),
      '{longitude}',to_jsonb(u.lon),true),
      '{coordinate_source}',to_jsonb('recaap_incidents_2024_2026.csv'::text),true),
      updated_at=now()
 FROM unique_matches u WHERE e.event_id=u.event_id
 RETURNING e.event_id
)
SELECT (SELECT count(*) FROM recaap_geo_repair) AS csv_rows,
       (SELECT count(*) FROM recaap_geo_repair WHERE lat BETWEEN -90 AND 90 AND lon BETWEEN -180 AND 180) AS positioned_source_rows,
       count(*) AS updated_events
FROM updated;
COMMIT;
